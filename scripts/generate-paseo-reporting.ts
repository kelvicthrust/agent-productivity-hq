import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { parse } from 'yaml';

const root = resolve(import.meta.dirname, '..');
const client = resolve(root, 'plugins/paseo-agent-productivity/shared');
const header = '// Generated by scripts/generate-paseo-reporting.ts. Do not edit.\n\n';
const filters = readFileSync(resolve(root, 'src/shared/domain/dashboard-filters.ts'), 'utf8');
const design = readFileSync(resolve(root, 'design-system/DESIGN.md'), 'utf8');
const frontMatter = /^---\r?\n([\s\S]*?)\r?\n---/.exec(design)?.[1];
if (!frontMatter) throw new Error('Design tokens are missing their YAML front matter.');
const { colors } = parse(frontMatter) as { colors: Record<string, string> };
const colorLines = Object.entries(colors).map(([name, value]) => {
  const key = name.includes('-') ? `'${name}'` : name;
  return `  ${key}: '${value}',`;
});

const source = (file: string) => readFileSync(resolve(root, file), 'utf8');

function section(file: string, start: string, end?: string): string {
  const input = source(file);
  const first = input.indexOf(start);
  const last = end === undefined ? input.length : input.indexOf(end, first);
  if (first < 0 || last < first) throw new Error(`Missing reporting definitions in ${file}.`);
  return `${input.slice(first, last).trimEnd()}\n`;
}

const chart = 'src/client/components/AlignedChart';
const output = {
  '../client/native-nunito.generated.ts': `export const nunito = '${readFileSync(
    resolve(root, 'src/client/theme/fonts/nunito-latin-wght.woff2'),
  ).toString('base64')}';\n`,
  'reporting-filters.ts': filters,
  'reporting-palette.ts': `export const colors = {\n${colorLines.join('\n')}\n} as const;\n`,
  'reporting-chart-layout.ts': [
    "import type { Bucket, Provider } from './report-contracts.ts';",
    "import { compactCount as compact } from './reporting-chart-utils.ts';",
    'import {',
    '  deliveryOf,',
    '  isUncovered,',
    '  providersIn,',
    '  providerTokens,',
    '  railOf,',
    "} from './reporting-chart-model.ts';",
    '',
    section(`${chart}/layout.ts`, "// The aligned chart's geometry"),
  ].join('\n'),
  'reporting-chart-model.ts': [
    "import type { Bucket, DeliveryCoverage, Provider, UsageCoverage } from './report-contracts.ts';",
    "import { railCoverage } from './reporting-chart-utils.ts';",
    '',
    section(`${chart}/model.ts`, '// What a series bucket means'),
  ].join('\n'),
  'reporting-chart-utils.ts': [
    "import type { UsageCoverage } from './report-contracts.ts';",
    '',
    section(
      'src/shared/domain/coverage.ts',
      '/** The one rail value',
      'export interface DeliveryCoverageInput',
    ),
    section('src/shared/domain/tokens.ts', '/** "1.2M"'),
  ].join('\n'),
  'reporting-year-layout.ts': [
    "import { addDays, diffDays, weekStart } from './reporting-filters.ts';",
    '',
    section(
      'src/client/components/YearGrid.tsx',
      "/**\n * The prototype's constants",
      '// ---- words',
    ),
  ].join('\n'),
  'reporting-greeting.ts': source('src/client/features/overview/greeting.ts'),
  'reporting-dates.ts': [
    section('src/shared/domain/periods.ts', 'const MONTHS', 'const DOW'),
    section(
      'src/shared/domain/periods.ts',
      'export const formatDay =',
      'export const formatMonth =',
    ),
    section('src/shared/domain/periods.ts', 'export function formatRange('),
  ].join('\n'),
};

// Paseo's client compiler only allows modules inside the installed plugin.
for (const [file, body] of Object.entries(output)) {
  const target = resolve(client, file);
  const content = header + body;
  if (process.argv.includes('--check')) {
    if (readFileSync(target, 'utf8') !== content) {
      throw new Error(`${file} is stale. Run node scripts/generate-paseo-reporting.ts.`);
    }
  } else {
    writeFileSync(target, content);
  }
}
