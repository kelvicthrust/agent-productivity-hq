import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { chromium } from '@playwright/test';
import { createElement } from 'react';
import { renderToStaticMarkup } from 'react-dom/server';
import {
  Ground,
  LINE_BOIL_SEEDS,
  LineBoilFilter,
  Roof,
} from '../plugins/paseo-agent-productivity/client/native-hq-art.generated.mjs';
import { hqColors } from '../plugins/paseo-agent-productivity/client/native-hq-palette.generated.ts';

const root = new URL('../', import.meta.url);
const source = [
  'scripts/generate-paseo-hq-boil.ts',
  'src/client/features/hq/HqScene.tsx',
  'src/client/features/hq/sceneFilters.tsx',
  'src/client/features/hq/sketch.ts',
  'src/client/theme/generated/tokens.css',
];
const hashes = createHash('sha256');
for (const path of source) hashes.update(readFileSync(new URL(path, root)));
const header = [
  '// Generated by scripts/generate-paseo-hq-boil.ts with the pinned Playwright Chromium.',
  `// Source SHA-256: ${hashes.digest('hex')}`,
  '',
].join('\n');
const output = new URL('plugins/paseo-agent-productivity/client/native-hq-boil.generated.ts', root);

if (process.argv.includes('--check')) {
  if (!readFileSync(output, 'utf8').startsWith(header))
    throw new Error('Paseo HQ ink frames are stale');
} else {
  await generateFrames();
}

async function generateFrames() {
  const browser = await chromium.launch({
    executablePath: process.env.HQ_ART_CHROME || undefined,
    args: ['--force-color-profile=srgb'],
  });
  try {
    const page = await browser.newPage({
      viewport: { width: 1000, height: 60 },
      deviceScaleFactor: 1,
    });
    const art = { roof: [Roof(), 48], ground: [Ground(), 14] } as const;
    const colorRules = Object.entries(hqColors)
      .flatMap(([name, value]) => [
        `.fill-${name} { fill: ${value}; }`,
        `.stroke-${name} { stroke: ${value}; }`,
      ])
      .join('\n');
    const frames: Record<string, string[]> = {};
    for (const [name, [drawing, height]] of Object.entries(art)) {
      frames[name] = [];
      for (const seed of LINE_BOIL_SEEDS) {
        const defs = renderToStaticMarkup(
          createElement(
            'svg',
            null,
            createElement('defs', null, LineBoilFilter({ id: 'ink', seed })),
          ),
        ).slice('<svg>'.length, -'</svg>'.length);
        const markup = renderToStaticMarkup(drawing).replace('><g ', `>${defs}<g `);
        await page.setContent(`<!doctype html><style>
          body { margin: 0; }
          svg { display: block; width: 1000px; height: ${height}px; }
          svg > g { filter: url(#ink); }
          .fill-none { fill: none; }
          ${colorRules}
          </style>${markup}`);
        const image = await page.screenshot({
          omitBackground: true,
          clip: { x: 0, y: 0, width: 1000, height },
        });
        frames[name].push(`data:image/png;base64,${image.toString('base64')}`);
      }
    }
    writeFileSync(
      fileURLToPath(output),
      `${header}export const inkFrames = ${JSON.stringify(frames, null, 2)} as const;\n`,
    );
  } finally {
    await browser.close();
  }
}
