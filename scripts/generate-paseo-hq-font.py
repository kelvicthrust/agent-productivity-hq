"""Extract outline glyphs from HQ's Playpen Sans WOFF2 with fonttools[woff]==4.63.0."""

import argparse
import json
from hashlib import sha256
from pathlib import Path

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont


ROOT = Path(__file__).resolve().parent.parent
FONT = ROOT / "src/client/theme/fonts/playpen-sans-latin-wght.woff2"
OUTPUT = ROOT / "plugins/paseo-agent-productivity/client/native-hq-font.generated.ts"


def glyphs_for_weight(font: TTFont, weight: int, text: str | None = None) -> dict:
    instance = instantiateVariableFont(font, {"wght": weight})
    glyphs = instance.getGlyphSet()
    em = instance["head"].unitsPerEm
    result = {}
    for codepoint, name in instance.getBestCmap().items():
        character = chr(codepoint)
        if text is not None and character not in text:
            continue
        glyph = glyphs[name]
        pen = SVGPathPen(glyphs, ntos=lambda value: f"{value:.2f}".rstrip("0").rstrip("."))
        glyph.draw(TransformPen(pen, (100 / em, 0, 0, -100 / em, 0, 0)))
        result[character] = [round(glyph.width / em, 4), pen.getCommands()]
    return result


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="verify generated outlines")
    args = parser.parse_args()
    digest = sha256(FONT.read_bytes()).hexdigest()
    with TTFont(FONT) as font:
        weights = {
            weight: glyphs_for_weight(font, weight, text)
            for weight, text in ((400, None), (500, "backsoon"), (600, None), (700, "AFK"))
        }
    content = (
        "// Generated by scripts/generate-paseo-hq-font.py from Playpen Sans (SIL OFL 1.1).\n"
        f"// Source SHA-256: {digest}\n"
        "type Glyph = readonly [advance: number, path: string];\n"
        "export const playpen: Readonly<Record<number, Readonly<Record<string, Glyph>>>> = "
        + json.dumps(weights, ensure_ascii=True, separators=(",", ":"))
        + ";\n"
    )
    if args.check:
        if OUTPUT.read_text(encoding="utf-8") != content:
            raise SystemExit("Paseo HQ font outlines are stale")
    else:
        OUTPUT.write_text(content, encoding="utf-8")


if __name__ == "__main__":
    main()
