import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'vite';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const client = resolve(root, 'plugins/paseo-agent-productivity/client');
const feature = resolve(root, 'src/client/features/hq');
const entry = resolve(root, 'scripts/paseo-hq-art.virtual.ts');
const virtualEntry = '\0paseo-hq-art';

const bundle = await build({
  root,
  configFile: false,
  logLevel: 'silent',
  oxc: { jsx: { runtime: 'automatic', development: false } },
  build: {
    target: 'es2023',
    minify: false,
    write: false,
    lib: { entry, formats: ['es'], fileName: 'native-hq-art.generated' },
    rolldownOptions: { external: [/^react(?:\/|$)/] },
  },
  plugins: [
    {
      name: 'paseo-hq-art',
      resolveId: (id) => (id === entry ? virtualEntry : undefined),
      load: (id) =>
        id === virtualEntry
          ? `export { Room, EmptyRoom, ROOM_HEIGHT, ROOM_HEIGHT_TALL } from ${JSON.stringify(`${feature}/Room.tsx`)};
export { AfkRoom } from ${JSON.stringify(`${feature}/AfkScene.tsx`)};
export { Heading, Roof, Vent, Ground } from ${JSON.stringify(`${feature}/HqScene.tsx`)};
export { LINE_BOIL_SEEDS, LineBoilFilter } from ${JSON.stringify(`${feature}/sceneFilters.tsx`)};
export { Buddy } from ${JSON.stringify(resolve(root, 'src/client/components/Buddy.tsx'))};
export { CrewArt } from ${JSON.stringify(resolve(root, 'src/client/components/CrewArt.tsx'))};
export { layoutScene } from ${JSON.stringify(`${feature}/scene.ts`)};
export { buildSessions } from ${JSON.stringify(`${feature}/sessions.ts`)};
export { stateWords, summaryLine } from ${JSON.stringify(`${feature}/copy.ts`)};
export { captionsCollide, planStage } from ${JSON.stringify(`${feature}/stage.ts`)};`
          : undefined,
    },
  ],
});

const result = Array.isArray(bundle) ? bundle[0] : bundle;
if (!result || !('output' in result)) throw new Error('Expected compiled Paseo HQ art');
const chunk = result.output[0];
if (chunk?.type !== 'chunk') throw new Error('Expected one JavaScript module for Paseo HQ art');
const header = '// Generated by scripts/generate-paseo-hq-art.ts. Edit the original HQ sources.\n';
const tokens = readFileSync(resolve(root, 'src/client/theme/generated/tokens.css'), 'utf8');
const colors = Object.fromEntries(
  Array.from(tokens.matchAll(/--color-([\w-]+):\s*(#[\da-fA-F]+);/g), ([, name, value]) => [
    name,
    value,
  ]),
);
const palette = {
  ...colors,
  ink: colors.text,
  'ink-muted': colors['text-muted'],
  sunken: colors['surface-sunken'],
  white: colors.surface,
};

const outputs = [
  ['native-hq-art.generated.mjs', chunk.code],
  [
    'native-hq-palette.generated.ts',
    `export const hqColors = ${JSON.stringify(palette, null, 2)} as const;\n`,
  ],
] as const;
for (const [name, body] of outputs) {
  const path = resolve(client, name);
  const content = header + body;
  if (process.argv.includes('--check')) {
    if (readFileSync(path, 'utf8') !== content) throw new Error(`${name} is stale`);
  } else {
    writeFileSync(path, content);
  }
}
